"""Build the Atlas favicon ("torn sky", six-colour stripes) from one scene description.

The sky sphere Atlas carries, cut into six horizontal slices that slide apart,
coloured cool to warm in the site's own palette.

Writes:
  sources/favicon/atlas-icon.svg   vector reference of the same scene
  public/favicon.ico               16/32/48 px, rounded tile
  public/apple-touch-icon.png      180 px, square tile (iOS rounds it)

Run from the repo root: python3 -I sources/favicon/build_icons.py
Needs numpy + Pillow. Rasterizes with supersampling, so no SVG renderer is required.
"""
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
GRID = 32      # the scene is drawn on a 32×32 grid
TILE_RX = 7    # corner radius of the tab icon

BG = (0x04, 0x1c, 0x1c)          # page --bg
CX, CY, R = 16, 16, 12           # the sphere
TOP, BOTTOM, GAP = 4, 28, .55    # slices fill TOP..BOTTOM, separated by GAP
# One slice per row, top to bottom: (horizontal shift, rgb)
SLICES = [
    (-1.5, (0x80, 0xaa, 0x8c)),   # mint
    (1, (0x3e, 0x8c, 0x76)),      # sea green
    (-.5, (0xff, 0xe6, 0xcb)),    # cream (page --fg)
    (2, (0xf0, 0xb6, 0x92)),      # peach
    (-2, (0xcf, 0x7c, 0x60)),     # terracotta (signature dot)
    (1, (0xaa, 0x54, 0x3c)),      # rust
]


def slice_rows():
    h = (BOTTOM - TOP - GAP * (len(SLICES) - 1)) / len(SLICES)
    for i, (dx, rgb) in enumerate(SLICES):
        y0 = TOP + i * (h + GAP)
        yield y0, y0 + h, dx, rgb


# ---------- raster ----------

def rounded_rect(x, y, rx):
    if rx == 0:
        return np.ones_like(x)
    cx = np.clip(x, rx, GRID - rx)
    cy = np.clip(y, rx, GRID - rx)
    return (np.hypot(x - cx, y - cy) <= rx).astype(float)


def render(size, rx, ss):
    n = size * ss
    c = (np.arange(n) + .5) / n * GRID
    x, y = np.meshgrid(c, c)
    rgb = np.broadcast_to(np.array(BG, float), (n, n, 3)).copy()
    for y0, y1, dx, col in slice_rows():
        m = (y >= y0) & (y < y1) & (np.hypot(x - (CX + dx), y - CY) <= R)
        rgb[m] = col
    alpha = rounded_rect(x, y, rx)
    out = np.concatenate([rgb / 255 * alpha[..., None], alpha[..., None]], -1)  # premultiplied
    out = out.reshape(size, ss, size, ss, 4).mean((1, 3))  # box-filter downsample
    a = out[..., 3:]
    px = np.concatenate([np.where(a > 0, out[..., :3] / np.maximum(a, 1e-9), 0), a], -1)
    return Image.fromarray(np.round(px * 255).astype(np.uint8), "RGBA")


# ---------- svg ----------

def svg():
    defs, body = [], [f'<rect width="{GRID}" height="{GRID}" fill="rgb{BG}"/>']
    for i, (y0, y1, dx, rgb) in enumerate(slice_rows()):
        defs.append(f'<clipPath id="s{i}"><rect y="{y0:.3f}" width="{GRID}" height="{y1 - y0:.3f}"/></clipPath>')
        body.append(f'<circle cx="{CX + dx:g}" cy="{CY}" r="{R}" fill="rgb{rgb}" clip-path="url(#s{i})"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {GRID} {GRID}">\n'
            "<!-- Atlas favicon (torn sky, six-colour stripes). Generated by build_icons.py; edit the script, not this file. -->\n"
            f'<defs>{"".join(defs)}<clipPath id="tile"><rect width="{GRID}" height="{GRID}" rx="{TILE_RX}"/></clipPath></defs>\n'
            '<g clip-path="url(#tile)">\n' + "\n".join(body) + "\n</g>\n</svg>\n")


def main():
    (ROOT / "sources/favicon/atlas-icon.svg").write_text(svg())
    ico = [render(s, TILE_RX, 8) for s in (48, 32, 16)]
    ico[0].save(ROOT / "public/favicon.ico", sizes=[(48, 48), (32, 32), (16, 16)], append_images=ico[1:])
    render(180, 0, 4).convert("RGB").save(ROOT / "public/apple-touch-icon.png", optimize=True)
    for f in ("public/favicon.ico", "public/apple-touch-icon.png", "sources/favicon/atlas-icon.svg"):
        print(f, (ROOT / f).stat().st_size, "bytes")


if __name__ == "__main__":
    main()
